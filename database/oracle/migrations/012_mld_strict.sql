CREATE OR REPLACE VIEW services AS
SELECT s.id_serv id,s.ref_service name,s.prestation description,
 (SELECT MIN(e.nom||' '||e.prenom) FROM employer e WHERE e.id_serv=s.id_serv) responsible,
 s.categorie category,s.date_heur datetime,s.statut status,s.duree duration,s.tarif price,
 s.ref_service clientname,CAST(NULL AS VARCHAR2(60)) invoicenumber,
 CAST(NULL AS VARCHAR2(35)) invoicedate,'BROUILLON' invoice_status,
 CAST(NULL AS VARCHAR2(35)) invoice_emitted_at FROM service s;
CREATE OR REPLACE VIEW locaux AS
SELECT id_local id,nom_local name,type,etage floor,capacite capacity,
 CASE WHEN etat='Occupé' THEN 1 ELSE 0 END occupancy,specialite specialty,
 CASE WHEN etat='Hors service' THEN 1 ELSE 0 END out_of_service,
 0 cleaning,CAST(NULL AS VARCHAR2(35)) last_cleaned,CAST(NULL AS VARCHAR2(35)) dirty_since,id_serv id_service,etat FROM local;
CREATE OR REPLACE VIEW stock_lots AS
SELECT lot,article,type_article category,quantite_disp quantity,'unité' unit,seuil_min threshold,
 date_echeance expiry,id_local,id_article,nom_article FROM stock;
CREATE OR REPLACE VIEW employes AS
SELECT id_emp id,nom,prenom,courriel,tel telephone,poste,date_embauche,disponible,
 charge charge_hebdo,dispo_repos dispo_hebdo,competences,id_serv id_service,
 cin,date_naiss,adresse,type_contrat,salaire FROM employer;
CREATE OR REPLACE VIEW medical_records AS
SELECT id_doss id,id_animal animal_id,nom_animal name,espece species,race breed,age,sexe sex,
 proprietaire,date_consultation consultation_date,motif reason,diagnostic diagnosis,
 CAST(NULL AS VARCHAR2(4000)) treatment,CAST(NULL AS VARCHAR2(4000)) vaccinations,
 CAST(NULL AS VARCHAR2(4000)) allergies,CAST(NULL AS NUMBER) weight,
 CAST(NULL AS VARCHAR2(4000)) observations,CAST(NULL AS VARCHAR2(30)) vaccination_status,id_emp id_employe FROM medical;
CREATE OR REPLACE VIEW planning_affectations AS
SELECT e.id_emp id,s.ref_service titre,NVL(e.competences,'Service') competence_requise,
 REPLACE(SUBSTR(s.date_heur,1,19),'T',' ') debut,
 TO_CHAR(TO_TIMESTAMP(SUBSTR(s.date_heur,1,19),'YYYY-MM-DD"T"HH24:MI:SS')+NUMTODSINTERVAL(s.duree,'MINUTE'),'YYYY-MM-DD HH24:MI:SS') fin,
 s.duree/60 charge_heures,e.id_emp responsable_id,s.date_heur created_at
FROM employer e JOIN service s ON s.id_serv=e.id_serv WHERE s.statut<>'Annulé' WITH READ ONLY;
