CREATE OR REPLACE TRIGGER lignes_facture_protection
BEFORE INSERT OR UPDATE OR DELETE ON lignes_facture FOR EACH ROW
DECLARE s VARCHAR2(12);
BEGIN
 IF UPDATING OR DELETING THEN
  SELECT statut INTO s FROM factures WHERE id=:OLD.id_facture;
  IF s<>'BROUILLON' THEN RAISE_APPLICATION_ERROR(-20044,'Ligne de facture emise non modifiable.'); END IF;
 END IF;
