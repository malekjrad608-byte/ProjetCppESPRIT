CREATE OR REPLACE TRIGGER factures_protection_bud
BEFORE UPDATE OR DELETE ON factures FOR EACH ROW
BEGIN
 IF DELETING AND :OLD.statut IN ('EMISE','ANNULEE') THEN RAISE_APPLICATION_ERROR(-20042,'Conservez la facture emise ou annulee dans l historique.'); END IF;
 IF UPDATING AND :OLD.statut IN ('EMISE','ANNULEE') THEN
  IF :NEW.statut='BROUILLON' OR (:OLD.statut='ANNULEE' AND :NEW.statut<>'ANNULEE') OR
    (:NEW.id_service IS NOT NULL AND NVL(:NEW.id_service,-1)<>NVL(:OLD.id_service,-1)) OR
    :NEW.total<>:OLD.total OR :NEW.numero<>:OLD.numero OR :NEW.service_reference<>:OLD.service_reference OR
    NVL(:NEW.id_client,-1)<>NVL(:OLD.id_client,-1) OR NVL(:NEW.nom_client,CHR(1))<>NVL(:OLD.nom_client,CHR(1)) OR
    :NEW.service_nom<>:OLD.service_nom OR NVL(:NEW.categorie,CHR(1))<>NVL(:OLD.categorie,CHR(1)) OR
    NVL(:NEW.responsable,CHR(1))<>NVL(:OLD.responsable,CHR(1)) OR
    NVL(:NEW.date_service,CHR(1))<>NVL(:OLD.date_service,CHR(1)) OR NVL(:NEW.duree,-1)<>NVL(:OLD.duree,-1) OR
    NVL(:NEW.date_creation,CHR(1))<>NVL(:OLD.date_creation,CHR(1)) OR
    NVL(:NEW.date_emission,TIMESTAMP '1900-01-01 00:00:00')<>NVL(:OLD.date_emission,TIMESTAMP '1900-01-01 00:00:00') THEN
   RAISE_APPLICATION_ERROR(-20043,'Les informations de la facture emise sont figees.');
  END IF;
 END IF;
END;
