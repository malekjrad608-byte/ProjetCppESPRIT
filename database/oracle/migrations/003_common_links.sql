DECLARE
 n NUMBER;
 PROCEDURE ddl_if_missing(object_name VARCHAR2, sql_text VARCHAR2) IS
 BEGIN
  SELECT COUNT(*) INTO n FROM all_tables WHERE owner=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND table_name=object_name;
  IF n=0 THEN EXECUTE IMMEDIATE sql_text; END IF;
 END;
 PROCEDURE add_column(t VARCHAR2,c VARCHAR2,definition VARCHAR2) IS
 BEGIN
  SELECT COUNT(*) INTO n FROM all_tab_columns WHERE owner=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND table_name=t AND column_name=c;
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE '||t||' ADD ('||definition||')'; END IF;
 END;
 PROCEDURE constraint_once(t VARCHAR2,c VARCHAR2,definition VARCHAR2) IS
 BEGIN
  SELECT COUNT(*) INTO n FROM all_constraints WHERE owner=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND constraint_name=c;
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE '||t||' ADD CONSTRAINT '||c||' '||definition; END IF;
 END;
 PROCEDURE index_once(i VARCHAR2,definition VARCHAR2) IS
 BEGIN
  SELECT COUNT(*) INTO n FROM all_indexes WHERE owner=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND index_name=i;
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX '||i||' ON '||definition; END IF;
 END;
