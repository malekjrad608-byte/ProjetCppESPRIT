DECLARE
 n VARCHAR2(250); cid NUMBER; fstate VARCHAR2(12);
 FUNCTION changed(a VARCHAR2,b VARCHAR2) RETURN BOOLEAN IS
 BEGIN RETURN (a<>b OR (a IS NULL AND b IS NOT NULL) OR (a IS NOT NULL AND b IS NULL)); END;
BEGIN
 IF :NEW.id_employe IS NOT NULL THEN
  SELECT TRIM(nom||' '||prenom) INTO n FROM employes WHERE id=:NEW.id_employe;
  :NEW.responsible:=n;
 END IF;
 IF :NEW.id_client IS NOT NULL THEN
  SELECT nom INTO n FROM clients WHERE id=:NEW.id_client;
  :NEW.clientName:=n;
 ELSIF TRIM(:NEW.clientName) IS NOT NULL THEN
  -- One identity per explicit new client. Same names are not proof of identity.
  INSERT INTO clients(nom) VALUES(TRIM(:NEW.clientName)) RETURNING id INTO cid;
  :NEW.id_client:=cid;
 END IF;
 IF UPDATING THEN
  BEGIN SELECT statut INTO fstate FROM factures WHERE id_service=:OLD.id;
  EXCEPTION WHEN NO_DATA_FOUND THEN fstate:='BROUILLON'; END;
  IF fstate IN ('EMISE','ANNULEE') AND (
   changed(:NEW.name,:OLD.name) OR changed(:NEW.clientName,:OLD.clientName) OR
   changed(:NEW.id_client,:OLD.id_client) OR changed(:NEW.id_employe,:OLD.id_employe) OR :NEW.price<>:OLD.price OR
   NVL(DBMS_LOB.GETLENGTH(:NEW.description),0)<>NVL(DBMS_LOB.GETLENGTH(:OLD.description),0) OR
   NVL(DBMS_LOB.COMPARE(:NEW.description,:OLD.description),0)<>0 OR changed(:NEW.category,:OLD.category) OR
   :NEW.duration<>:OLD.duration OR changed(:NEW.datetime,:OLD.datetime) OR
   changed(:NEW.responsible,:OLD.responsible) OR changed(:NEW.invoicenumber,:OLD.invoicenumber) OR
   changed(:NEW.invoicedate,:OLD.invoicedate)) THEN
   RAISE_APPLICATION_ERROR(-20041,'Facture emise : informations facturees figees. Creez une nouvelle prestation pour une correction.');
  END IF;
 END IF;
END;
