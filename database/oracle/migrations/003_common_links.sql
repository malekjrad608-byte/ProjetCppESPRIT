CREATE OR REPLACE TRIGGER services_facture_aiu
AFTER INSERT OR UPDATE ON services FOR EACH ROW
DECLARE fid NUMBER; fstate VARCHAR2(12);
BEGIN
 BEGIN SELECT id,statut INTO fid,fstate FROM factures WHERE id_service=:NEW.id;
 EXCEPTION WHEN NO_DATA_FOUND THEN
  INSERT INTO factures(id_service,service_reference,id_client,numero,date_creation,nom_client,service_nom,categorie,responsable,date_service,duree,total)
   VALUES(:NEW.id,:NEW.id,:NEW.id_client,:NEW.invoiceNumber,:NEW.invoiceDate,:NEW.clientName,:NEW.name,:NEW.category,:NEW.responsible,:NEW.dateTime,:NEW.duration,:NEW.price) RETURNING id INTO fid;
  fstate:='BROUILLON';
 END;
 IF fstate='BROUILLON' THEN
  UPDATE factures SET id_client=:NEW.id_client,nom_client=:NEW.clientName,service_nom=:NEW.name,categorie=:NEW.category,
   responsable=:NEW.responsible,date_service=:NEW.dateTime,duree=:NEW.duration,total=:NEW.price WHERE id=fid;
  MERGE INTO lignes_facture l USING (SELECT fid id FROM dual) s ON(l.id_facture=s.id AND l.numero_ligne=1)
   WHEN MATCHED THEN UPDATE SET designation=:NEW.name,prestations=:NEW.description,prix_unitaire=:NEW.price
   WHEN NOT MATCHED THEN INSERT(id_facture,numero_ligne,designation,prestations,prix_unitaire) VALUES(fid,1,:NEW.name,:NEW.description,:NEW.price);
 END IF;
 IF :NEW.status='Annulé' THEN UPDATE factures SET statut='ANNULEE' WHERE id=fid; END IF;
END;
