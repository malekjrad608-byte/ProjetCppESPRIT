
  CREATE OR REPLACE NONEDITIONABLE TRIGGER "RAWAND"."SERVICES_TRG"
BEFORE INSERT ON SERVICES
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID IS NULL THEN
      SELECT SERVICES_SEQ1.NEXTVAL INTO :NEW.ID FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;
